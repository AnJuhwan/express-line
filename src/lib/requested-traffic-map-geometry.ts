export function buildOsmTiles(viewport: RequestedTrafficMapViewport): OsmTile[] {
  const topLeft = latLngToTileFraction({ lat: viewport.north, lng: viewport.west }, viewport.zoom);
  const bottomRight = latLngToTileFraction({ lat: viewport.south, lng: viewport.east }, viewport.zoom);
  const minX = Math.floor(topLeft.x);
  const maxX = Math.floor(bottomRight.x);
  const minY = Math.floor(topLeft.y);
  const maxY = Math.floor(bottomRight.y);
  const xSpan = bottomRight.x - topLeft.x;
  const ySpan = bottomRight.y - topLeft.y;
  const tiles: OsmTile[] = [];

  for (let x = minX; x <= maxX; x += 1) {
    for (let y = minY; y <= maxY; y += 1) {
      tiles.push({
        key: `${viewport.zoom}-${x}-${y}`,
        url: `https://tile.openstreetmap.org/${viewport.zoom}/${x}/${y}.png`,
        leftPercent: ((x - topLeft.x) / xSpan) * 100,
        topPercent: ((y - topLeft.y) / ySpan) * 100,
        widthPercent: (1 / xSpan) * 100,
        heightPercent: (1 / ySpan) * 100
      });
    }
  }

  return tiles;
}

export function projectLatLngToPercent(point: LatLng, viewport: RequestedTrafficMapViewport): ProjectedPoint {
  const topLeft = latLngToWorld({ lat: viewport.north, lng: viewport.west });
  const bottomRight = latLngToWorld({ lat: viewport.south, lng: viewport.east });
  const projected = latLngToWorld(point);

  return {
    xPercent: ((projected.x - topLeft.x) / (bottomRight.x - topLeft.x)) * 100,
    yPercent: ((projected.y - topLeft.y) / (bottomRight.y - topLeft.y)) * 100
  };
}

export function buildCenteredRouteViewport(
  routeId: string,
  fallbackViewport: RequestedTrafficMapViewport
): RequestedTrafficMapViewport {
  const geometry = REQUESTED_TRAFFIC_ROUTE_GEOMETRIES[routeId];
  if (!geometry?.length) return fallbackViewport;

  return buildViewportForPath(geometry, fallbackViewport, {
    latPaddingRatio: 0.14,
    lngPaddingRatio: 0.06,
    minLatPadding: 0.006,
    minLngPadding: 0.006,
    zoomIncrement: 2
  });
}

export function buildRouteDistanceSplitViewports(
  routeId: string,
  fallbackViewport: RequestedTrafficMapViewport,
  splitCount = 2
): RequestedTrafficRouteDistanceSplit[] {
  const geometry = REQUESTED_TRAFFIC_ROUTE_GEOMETRIES[routeId];
  if (!geometry?.length || splitCount < 1) return [];

  return Array.from({ length: splitCount }, (_, index) => {
    const startRatio = index / splitCount;
    const endRatio = (index + 1) / splitCount;
    const window = { startRatio, endRatio };
    const path = slicePathByRatio(geometry, startRatio, endRatio);

    return {
      ...window,
      key: `${routeId}-${index + 1}-of-${splitCount}`,
      caption: splitCaption(index, splitCount),
      meta: `거리 ${Math.round(startRatio * 100)}-${Math.round(endRatio * 100)}%`,
      startTerminalLabel: index === 0 ? "출발" : "중간",
      endTerminalLabel: index === splitCount - 1 ? "도착" : "중간",
      viewport: buildViewportForPath(path, fallbackViewport, {
        latPaddingRatio: 0.32,
        lngPaddingRatio: 0.12,
        minLatPadding: 0.008,
        minLngPadding: 0.008,
        zoomIncrement: 2
      })
    };
  });
}

export function buildFocusedTrafficViewport(
  routeId: string,
  segments: RequestedTrafficMapSegment[],
  fallbackViewport: RequestedTrafficMapViewport
): RequestedTrafficMapViewport {
  const blockedPoints = buildTrafficSegmentSlices(routeId, segments)
    .filter(({ segment }) => segment.status === "서행" || segment.status === "정체")
    .flatMap(({ points }) => points);

  if (blockedPoints.length < 2) return fallbackViewport;

  const bounds = latLngBounds(blockedPoints);
  const latSpan = Math.max(0.001, bounds.north - bounds.south);
  const lngSpan = Math.max(0.001, bounds.east - bounds.west);
  const targetLatSpan = Math.max(latSpan * 1.8, 0.018);
  const targetLngSpan = Math.max(lngSpan * 1.45, 0.028);
  const centerLat = (bounds.north + bounds.south) / 2;
  const centerLng = (bounds.east + bounds.west) / 2;

  return {
    north: centerLat + targetLatSpan / 2,
    south: centerLat - targetLatSpan / 2,
    west: centerLng - targetLngSpan / 2,
    east: centerLng + targetLngSpan / 2,
    zoom: Math.min(15, Math.max(fallbackViewport.zoom, 15))
  };
}

export function buildProjectedRoutePath(
  routeId: string,
  viewport: RequestedTrafficMapViewport,
  routeWindow?: RequestedTrafficRouteRatioWindow
): ProjectedPoint[] {
  const geometry = REQUESTED_TRAFFIC_ROUTE_GEOMETRIES[routeId] ?? [];
  const path = routeWindow ? slicePathByRatio(geometry, routeWindow.startRatio, routeWindow.endRatio) : geometry;
  return path.map((point) => projectLatLngToPercent(point, viewport));
}

export function buildProjectedRouteLandmarks(routeId: string, viewport: RequestedTrafficMapViewport): ProjectedRouteLandmark[] {
  return (REQUESTED_TRAFFIC_ROUTE_LANDMARKS[routeId] ?? [])
    .map((landmark) => ({
      label: landmark.label,
      ...projectLatLngToPercent(landmark.point, viewport)
    }))
    .filter((landmark) => landmark.xPercent > 0 && landmark.xPercent < 100 && landmark.yPercent > 0 && landmark.yPercent < 100);
}

export function buildProjectedTrafficSegmentPaths(
  routeId: string,
  segments: RequestedTrafficMapSegment[],
  viewport: RequestedTrafficMapViewport,
  routeWindow?: RequestedTrafficRouteRatioWindow
): ProjectedTrafficSegmentPath[] {
  return buildTrafficSegmentSlices(routeId, segments, routeWindow).map(({ segment, points }) => ({
    segment,
    points: points.map((point) => projectLatLngToPercent(point, viewport))
  }));
}

function buildTrafficSegmentSlices(
  routeId: string,
  segments: RequestedTrafficMapSegment[],
  routeWindow?: RequestedTrafficRouteRatioWindow
): Array<{ segment: RequestedTrafficMapSegment; points: LatLng[] }> {
  const geometry = REQUESTED_TRAFFIC_ROUTE_GEOMETRIES[routeId];
  if (!geometry?.length) return [];

  const window = normalizeRouteWindow(routeWindow);
  const totalSegmentLength = segments.reduce((sum, segment) => sum + Math.max(1, segment.lengthMeters), 0);
  let cursor = 0;

  return segments.flatMap((segment) => {
    const segmentLength = Math.max(1, segment.lengthMeters);
    const rawStartRatio = totalSegmentLength > 0 ? cursor / totalSegmentLength : 0;
    cursor += segmentLength;
    const rawEndRatio = totalSegmentLength > 0 ? cursor / totalSegmentLength : 1;
    const overlapRatio = Math.min(0.003, Math.max(0.0008, segmentLength / totalSegmentLength / 4));
    const startRatio = Math.max(window.startRatio, rawStartRatio - overlapRatio);
    const endRatio = Math.min(window.endRatio, rawEndRatio + overlapRatio);

    if (endRatio <= startRatio) return [];

    return [{
      segment,
      points: slicePathByRatio(geometry, startRatio, endRatio)
    }];
  });
}

function buildViewportForPath(
  path: LatLng[],
  fallbackViewport: RequestedTrafficMapViewport,
  options: {
    latPaddingRatio: number;
    lngPaddingRatio: number;
    minLatPadding: number;
    minLngPadding: number;
    zoomIncrement: number;
  }
): RequestedTrafficMapViewport {
  if (!path.length) return fallbackViewport;

  const bounds = latLngBounds(path);
  const latSpan = Math.max(0.001, bounds.north - bounds.south);
  const lngSpan = Math.max(0.001, bounds.east - bounds.west);
  const latPadding = Math.max(latSpan * options.latPaddingRatio, options.minLatPadding);
  const lngPadding = Math.max(lngSpan * options.lngPaddingRatio, options.minLngPadding);

  return expandViewportToAspectRatio({
    north: bounds.north + latPadding,
    south: bounds.south - latPadding,
    west: bounds.west - lngPadding,
    east: bounds.east + lngPadding,
    zoom: Math.min(15, fallbackViewport.zoom + options.zoomIncrement)
  });
}

function expandViewportToAspectRatio(
  viewport: RequestedTrafficMapViewport,
  targetAspectRatio = MAP_DISPLAY_ASPECT_RATIO
): RequestedTrafficMapViewport {
  const topLeft = latLngToWorld({ lat: viewport.north, lng: viewport.west });
  const bottomRight = latLngToWorld({ lat: viewport.south, lng: viewport.east });
  const xSpan = bottomRight.x - topLeft.x;
  const ySpan = bottomRight.y - topLeft.y;
  const currentAspectRatio = xSpan / ySpan;
  const center = {
    x: (topLeft.x + bottomRight.x) / 2,
    y: (topLeft.y + bottomRight.y) / 2
  };

  if (currentAspectRatio < targetAspectRatio) {
    const targetXSpan = ySpan * targetAspectRatio;
    return {
      ...viewport,
      west: worldXToLng(center.x - targetXSpan / 2),
      east: worldXToLng(center.x + targetXSpan / 2)
    };
  }

  if (currentAspectRatio > targetAspectRatio) {
    const targetYSpan = xSpan / targetAspectRatio;
    return {
      ...viewport,
      north: worldYToLat(center.y - targetYSpan / 2),
      south: worldYToLat(center.y + targetYSpan / 2)
    };
  }

  return viewport;
}

function densifyRoutePath(path: LatLng[], maxEdgeMeters = 900): LatLng[] {
  if (path.length <= 1) return path;

  return path.slice(0, -1).flatMap((point, index) => {
    const nextPoint = path[index + 1];
    const edgeDistance = distanceMeters(point, nextPoint);
    const steps = Math.max(1, Math.ceil(edgeDistance / maxEdgeMeters));
    const points = index === 0 ? [point] : [];

    for (let step = 1; step <= steps; step += 1) {
      points.push(interpolate(point, nextPoint, step / steps));
    }

    return points;
  });
}

function connectToRoute(connector: LatLng[], route: LatLng[]): LatLng[] {
  const joinPoint = connector.at(-1);
  if (!joinPoint) return route;
  const index = nearestPointIndex(route, joinPoint);
  return [...connector, ...route.slice(index + 1)];
}

function connectFromRoute(route: LatLng[], connector: LatLng[]): LatLng[] {
  const joinPoint = connector.at(-1);
  if (!joinPoint) return route;
  const index = nearestPointIndex(route, joinPoint);
  return [...route.slice(0, index + 1), ...connector.slice(0, -1).reverse()];
}

function nearestPointIndex(path: LatLng[], target: LatLng): number {
  if (!path.length) return 0;
  return path.reduce((nearest, point, index) => (
    distanceMeters(point, target) < distanceMeters(path[nearest], target) ? index : nearest
  ), 0);
}

function normalizeRouteWindow(routeWindow?: RequestedTrafficRouteRatioWindow): RequestedTrafficRouteRatioWindow {
  if (!routeWindow) return { startRatio: 0, endRatio: 1 };

  const startRatio = Math.max(0, Math.min(1, routeWindow.startRatio));
  const endRatio = Math.max(0, Math.min(1, routeWindow.endRatio));
  return startRatio <= endRatio
    ? { startRatio, endRatio }
    : { startRatio: endRatio, endRatio: startRatio };
}

function splitCaption(index: number, splitCount: number): string {
  if (splitCount === 1) return "전체 구간";
  if (splitCount === 2) return index === 0 ? "전반 50%" : "후반 50%";
  return `${Math.round((index / splitCount) * 100)}-${Math.round(((index + 1) / splitCount) * 100)}%`;
}

function latLngBounds(points: LatLng[]): { north: number; south: number; west: number; east: number } {
  return points.reduce(
    (current, point) => ({
      north: Math.max(current.north, point.lat),
      south: Math.min(current.south, point.lat),
      west: Math.min(current.west, point.lng),
      east: Math.max(current.east, point.lng)
    }),
    {
      north: -90,
      south: 90,
      west: 180,
      east: -180
    }
  );
}

function slicePathByRatio(path: LatLng[], startRatio: number, endRatio: number): LatLng[] {
  if (path.length <= 1) return path;

  const distances = pathSegmentDistances(path);
  const totalDistance = distances.reduce((sum, distance) => sum + distance, 0);
  const startDistance = totalDistance * Math.max(0, Math.min(1, startRatio));
  const endDistance = totalDistance * Math.max(0, Math.min(1, endRatio));
  const points: LatLng[] = [];
  let traversed = 0;

  for (let index = 0; index < distances.length; index += 1) {
    const edgeStart = traversed;
    const edgeEnd = traversed + distances[index];
    const edgeStartPoint = path[index];
    const edgeEndPoint = path[index + 1];

    if (edgeEnd >= startDistance && edgeStart <= endDistance) {
      const clippedStart = Math.max(edgeStart, startDistance);
      const clippedEnd = Math.min(edgeEnd, endDistance);
      const startPoint = interpolate(edgeStartPoint, edgeEndPoint, ratioOnEdge(clippedStart, edgeStart, edgeEnd));
      const endPoint = interpolate(edgeStartPoint, edgeEndPoint, ratioOnEdge(clippedEnd, edgeStart, edgeEnd));

      if (!points.length || !samePoint(points.at(-1), startPoint)) points.push(startPoint);
      if (!samePoint(points.at(-1), endPoint)) points.push(endPoint);
    }

    traversed = edgeEnd;
  }

  return points.length >= 2 ? points : [path[0], path[1]];
}

function pathSegmentDistances(path: LatLng[]): number[] {
  return path.slice(0, -1).map((point, index) => distanceMeters(point, path[index + 1]));
}

function ratioOnEdge(distance: number, start: number, end: number): number {
  return end === start ? 0 : (distance - start) / (end - start);
}

function interpolate(start: LatLng, end: LatLng, ratio: number): LatLng {
  return {
    lat: start.lat + (end.lat - start.lat) * ratio,
    lng: start.lng + (end.lng - start.lng) * ratio
  };
}

function samePoint(a: LatLng | undefined, b: LatLng): boolean {
  return Boolean(a && Math.abs(a.lat - b.lat) < 0.000001 && Math.abs(a.lng - b.lng) < 0.000001);
}

function distanceMeters(a: LatLng, b: LatLng): number {
  const earthRadiusMeters = 6371000;
  const deltaLat = toRadians(b.lat - a.lat);
  const deltaLng = toRadians(b.lng - a.lng);
  const lat1 = toRadians(a.lat);
  const lat2 = toRadians(b.lat);
  const h =
    Math.sin(deltaLat / 2) * Math.sin(deltaLat / 2) +
    Math.cos(lat1) * Math.cos(lat2) * Math.sin(deltaLng / 2) * Math.sin(deltaLng / 2);
  return 2 * earthRadiusMeters * Math.atan2(Math.sqrt(h), Math.sqrt(1 - h));
}

function latLngToTileFraction(point: LatLng, zoom: number): { x: number; y: number } {
  const world = latLngToWorld(point);
  const scale = 2 ** zoom;
  return {
    x: world.x * scale,
    y: world.y * scale
  };
}

function latLngToWorld(point: LatLng): { x: number; y: number } {
  const sinLat = Math.sin(toRadians(point.lat));
  return {
    x: (point.lng + 180) / 360,
    y: 0.5 - Math.log((1 + sinLat) / (1 - sinLat)) / (4 * Math.PI)
  };
}

function worldXToLng(x: number): number {
  return x * 360 - 180;
}

function worldYToLat(y: number): number {
  return toDegrees(Math.atan(Math.sinh(Math.PI * (1 - 2 * y))));
}

function toRadians(degrees: number): number {
  return (degrees * Math.PI) / 180;
}

function toDegrees(radians: number): number {
  return (radians * 180) / Math.PI;
}

function landmark(label: string, lat: number, lng: number): { label: string; point: LatLng } {
  return { label, point: { lat, lng } };
}
